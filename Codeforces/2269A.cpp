void solve(){
    
    int n,k; cin>>n>>k;
    ll ans = 0;
    for(int i = 1; i <= k-1; i++) {
        ans += 2ll;
    }
    n -= k - 1;
    ll now = 1;
    for(int i = 1; i <= n; i++) {
        now *= 2ll;
    }
    ans += now;
    cout << ans << nl;
}

int main(){
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int t = 1;

    //setIO("");
    cin>>t;
    while(t--)solve();

    return 0;
}

